"""v3: the restore-incident loop - a "not safe" backup check becomes an IT incident.

When a restore *check* comes back FAIL, an incident opens so the clinic's IT contact
(``clinic.it_contact_name`` - a real person, not a staff row) is alerted with the
actionable steps from the failed checks. IT marks it resolved with what they did; the
owner is notified, retests the backup, and closes the incident when the next check is
safe - or sends it back to IT if it still isn't.

It mirrors the v2 ``alerts/it.py`` loop but lives on its own ``restore_incidents``
table, so it never touches the alerts or role-notification lanes. One active
(open/resolved) incident at a time: a fresh failing check reopens it instead of
stacking a second one.

    check FAIL -> open (IT alerted with fix steps)
    IT resolve -> resolved (owner notified) -> owner retests
    retest PASS -> owner closes          (or sends it back to IT -> open again)
"""
from __future__ import annotations

import json

from clock import Clock, now_iso
from config import Config
from db import Database
from errors import ApiError

RESOLVED_NOTE_MIN = 5   # IT says what they did, so the owner can check it (like alerts/it.py)


def _active(db: Database) -> dict | None:
    """The open or resolved incident (the most recent one that isn't closed), or None."""
    row = db.one("SELECT * FROM restore_incidents WHERE status IN ('open','resolved')"
                 " ORDER BY id DESC LIMIT 1")
    return row


def _fix_steps(checks: list[dict]) -> list[str]:
    """The actionable steps from the checks that failed - deduped, in check order."""
    seen, out = set(), []
    for c in checks:
        fix = c.get("fix")
        if not c["passed"] and fix and fix not in seen:
            seen.add(fix)
            out.append(fix)
    return out


def after_check(db: Database, clock: Clock, config: Config, run_id: int,
                result: str, checks: list[dict]) -> int | None:
    """Called after a restore check run. A FAIL opens (or reopens) the active incident;
    a PASS just refreshes its result so the owner's retest is reflected. Returns the
    incident id, or None when a PASS found no active incident."""
    now_text = now_iso(clock)
    active = _active(db)
    if active is not None:
        status = "open" if result == "FAIL" else active["status"]
        steps = [] if result == "PASS" else _fix_steps(checks)
        db.execute("UPDATE restore_incidents SET status=?, last_result=?, last_run_id=?, fix_steps=?"
                   " WHERE id=?", (status, result, run_id, json.dumps(steps), active["id"]))
        if result == "FAIL":
            db.emit("restore.incident_reopened", subject=("restore_incident", active["id"]))
        return active["id"]
    if result == "PASS":
        return None                     # a safe check with nothing open opens no incident
    incident_id = db.execute(
        "INSERT INTO restore_incidents (status, last_result, fix_steps, last_run_id, created_at)"
        " VALUES ('open', ?, ?, ?, ?)",
        (result, json.dumps(_fix_steps(checks)), run_id, now_text))
    db.emit("restore.incident_opened", subject=("restore_incident", incident_id), result=result)
    return incident_id


def _view(row: dict) -> dict:
    out = dict(row)
    out["fix_steps"] = json.loads(out["fix_steps"])
    return {
        "id": out["id"], "status": out["status"], "last_result": out["last_result"],
        "fix_steps": out["fix_steps"], "last_run_id": out["last_run_id"],
        "it_resolved_at": out["it_resolved_at"], "it_resolved_note": out["it_resolved_note"],
        "it_sent_back_at": out["it_sent_back_at"], "it_sent_back_note": out["it_sent_back_note"],
        "closed_at": out["closed_at"], "closed_by": out["closed_by"], "created_at": out["created_at"],
    }


def active(db: Database) -> dict | None:
    row = _active(db)
    return _view(row) if row else None


def list_all(db: Database) -> list[dict]:
    return [_view(dict(r)) for r in db.query("SELECT * FROM restore_incidents ORDER BY id DESC")]


def resolve(db: Database, clock: Clock, config: Config, note: str) -> dict:
    """The IT contact marks the open incident resolved, saying what they did.

    In the demo layout this also *simulates IT's repair* - the faulty demo backup is rebuilt
    clean, so the owner's next retest can come back safe and the incident can be closed. A
    real backup drive is never regenerated by the app.
    """
    note = note.strip()
    if len(note) < RESOLVED_NOTE_MIN:
        raise ApiError("invalid_request", "Say what you did, so the owner can check it.", 400)
    active_row = _active(db)
    if active_row is None or active_row["status"] != "open":
        raise ApiError("not_found", "There's no open backup incident to resolve.", 404)
    now_text = now_iso(clock)
    with db.transaction():
        db.execute("UPDATE restore_incidents SET status='resolved', it_resolved_at=?, it_resolved_note=?"
                   " WHERE id=?", (now_text, note, active_row["id"]))
        # The owner is a staff role, so this reaches the owner's notification poll; the IT
        # contact is reached by the incident showing up in /restore/incidents, not by a role.
        db.add_notification(f"{db.clinic()['it_contact_name']} says the backup is fixed: "
                           f"\"{note}\". Retest it and close it if it's safe.", now_text, to_role="owner")
        db.emit("restore.incident_resolved", subject=("restore_incident", active_row["id"]))
    _repair_demo_backup(config)
    return active(db)


def _repair_demo_backup(config: Config) -> None:
    """Demo-only: build IT's repaired backup as a *separate* clean tree (``backup_new/``),
    leaving the old faulty ``backup/`` in place as the baseline. No-op on a real backup
    drive (RESTORE_BACKUP_DIR pointed elsewhere). The next check targets the new tree.

    Stand-in for IT's real repair; must never break the incident state.
    """
    from demo_backup import make
    if config.restore_backup_dir != make.BACKUP_DIR:
        return
    try:
        make.build_new()
    except Exception:
        pass   # the repair is a demo convenience; it must never break the incident state


def close(db: Database, clock: Clock, staff_id: int, confirm: bool, note: str) -> dict:
    """The owner closes the incident after IT resolved it and a retest came back safe - or
    sends it back to IT when the retest still fails. Only the owner may close."""
    active_row = _active(db)
    if active_row is None:
        raise ApiError("not_found", "No open backup incident.", 404)
    if active_row["status"] != "resolved":
        raise ApiError("not_resolved", "IT hasn't marked the backup fixed yet.", 409)
    staff = db.staff(staff_id)
    if staff is None:
        raise ApiError("invalid_request", "Unknown staff member.", 400)
    if staff["role"] != "owner":
        raise ApiError("not_owner", "Only the owner can close the backup incident.", 403)
    now_text = now_iso(clock)
    with db.transaction():
        if confirm:
            latest = db.one("SELECT result FROM restore_runs WHERE kind='check' ORDER BY id DESC LIMIT 1")
            # Closing means the retest passed: the newest check must be the safe one.
            if latest is None or latest["result"] != "PASS":
                raise ApiError("invalid_request", "The last check isn't safe yet - retest and confirm it passes.", 409)
            db.execute("UPDATE restore_incidents SET status='closed', closed_at=?, closed_by=?"
                       " WHERE id=?", (now_text, staff_id, active_row["id"]))
        else:
            why = note.strip() or "Still not safe"
            db.execute("UPDATE restore_incidents SET status='open', it_resolved_at=NULL, it_resolved_note=NULL,"
                       " it_sent_back_at=?, it_sent_back_note=? WHERE id=?",
                       (now_text, why, active_row["id"]))
        db.emit("restore.incident_closed", actor=staff_id, subject=("restore_incident", active_row["id"]),
                confirmed=confirm)
    # Return the incident by id: after a confirmed close it is no longer "active", so
    # active() would come back None and the route's response model would reject it.
    row = db.one("SELECT * FROM restore_incidents WHERE id = ?", (active_row["id"],))
    return _view(row)
